create table public.ng_states (
  code text primary key check (code ~ '^[A-Z]{2}$'),
  name text not null unique
);

create table public.ng_lgas (
  id serial primary key,
  state_code text not null references public.ng_states(code),
  name text not null,
  unique (state_code, name)
);
create index ng_lgas_state_idx on public.ng_lgas (state_code);

alter table public.ng_states enable row level security;
alter table public.ng_lgas enable row level security;
create policy ng_states_read on public.ng_states for select to anon, authenticated using (true);
create policy ng_lgas_read on public.ng_lgas for select to anon, authenticated using (true);
grant select on public.ng_states, public.ng_lgas to anon, authenticated, service_role;
revoke insert, update, delete, truncate on public.ng_states, public.ng_lgas from anon, authenticated;

