-- =====================================================================
-- ACHIEVER — Nigerian administrative reference data
-- 36 states + FCT (ISO 3166-2:NG codes) and their 774 Local Government Areas.
-- Used for structured, validated addresses (country / state / LGA / city).
-- Verify spellings against the current official INEC/NBS listing before launch.
